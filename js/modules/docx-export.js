function _docEsc(s) {
  return String(s ?? '')
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;');
}

function buildWordHtml({ title, subtitle, metadata = [], sections = [], tables = [] }) {
  const metaHtml = metadata.length
    ? `<table style="width:100%;border-collapse:collapse;margin:12px 0 18px 0;font-size:10.5pt;">
         <tbody>${metadata.map(([k, v]) => `
           <tr>
             <th scope="row" style="text-align:left;padding:6px 10px;border:1px solid #cbd5e1;background:#f1f5f9;width:30%;color:#0f172a;">${_docEsc(k)}</th>
             <td style="padding:6px 10px;border:1px solid #cbd5e1;color:#1e293b;">${_docEsc(v)}</td>
           </tr>`).join('')}
         </tbody>
       </table>`
    : '';

  const tablesHtml = tables.map(t => `
    <h2 style="color:#004684;font-size:13pt;margin:18px 0 8px 0;border-bottom:1px solid #cbd5e1;padding-bottom:4px;">${_docEsc(t.heading)}</h2>
    <table style="width:100%;border-collapse:collapse;margin-bottom:14px;font-size:10.5pt;">
      <thead>
        <tr>${(t.headers || []).map(h => `<th scope="col" style="text-align:left;padding:7px 10px;border:1px solid #94a3b8;background:#004684;color:#ffffff;">${_docEsc(h)}</th>`).join('')}</tr>
      </thead>
      <tbody>
        ${(t.rows || []).map((row, idx) => `
          <tr style="background:${idx % 2 ? '#f8fafc' : '#ffffff'};">
            ${row.map(cell => `<td style="padding:6px 10px;border:1px solid #cbd5e1;color:#0f172a;">${_docEsc(cell)}</td>`).join('')}
          </tr>`).join('')}
      </tbody>
    </table>
  `).join('');

  const sectionsHtml = sections.map(sec => {
    const body = _docEsc(sec.body || '')
      .replace(/\[VERIFY[^\]]*\]/g, m => `<span style="background:#fef08a;font-weight:bold;padding:1px 3px;">${m}</span>`)
      .replace(/\n/g, '<br>');
    return `
      <h2 style="color:#004684;font-size:13pt;margin:18px 0 6px 0;border-bottom:1px solid #cbd5e1;padding-bottom:4px;">${_docEsc(sec.heading)}</h2>
      <p style="font-size:11pt;line-height:1.5;color:#1e293b;margin:0 0 12px 0;">${body}</p>
    `;
  }).join('');

  return `<!DOCTYPE html>
<html lang="en" xmlns:o="urn:schemas-microsoft-com:office:office" xmlns:w="urn:schemas-microsoft-com:office:word">
<head>
  <meta charset="utf-8">
  <title>${_docEsc(title || 'Granted Document')}</title>
  <style>
    @page { margin: 1in; }
    body { font-family: Calibri, Arial, sans-serif; color: #0f172a; line-height: 1.45; }
  </style>
</head>
<body>
  <h1 style="color:#004684;font-size:18pt;margin:0 0 4px 0;">${_docEsc(title || 'Granted Proposal Document')}</h1>
  ${subtitle ? `<p style="color:#475569;font-size:10.5pt;margin:0 0 14px 0;">${_docEsc(subtitle)}</p>` : ''}
  ${metaHtml}
  ${tablesHtml}
  ${sectionsHtml}
  <p style="margin-top:24px;font-size:8.5pt;color:#64748b;border-top:1px solid #e2e8f0;padding-top:8px;">
    Generated by Granted (thinkgrant.app) — Think! Design and Planning, LLC. Review all yellow [VERIFY] items prior to sponsor submission.
  </p>
</body>
</html>`;
}

function exportWordDocument(opts) {
  const html = buildWordHtml(opts);
  const blob = new Blob(['\ufeff', html], { type: 'application/msword;charset=utf-8' });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  const safeName = (opts.filename || 'granted-document').replace(/[^a-z0-9-_]+/gi, '-').toLowerCase();
  a.download = safeName.endsWith('.doc') ? safeName : `${safeName}.doc`;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  setTimeout(() => URL.revokeObjectURL(url), 1000);
}

if (typeof window !== 'undefined') {
  window.GRANTED_DOCX = { buildWordHtml, exportWordDocument };
}
if (typeof module !== 'undefined' && module.exports) {
  module.exports = { buildWordHtml };
}
